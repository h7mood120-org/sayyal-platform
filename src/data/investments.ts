import type { Investment, Distribution } from "@/lib/types";

const AR_MONTHS = [
  "يناير", "فبراير", "مارس", "أبريل", "مايو", "يونيو",
  "يوليو", "أغسطس", "سبتمبر", "أكتوبر", "نوفمبر", "ديسمبر",
];

/** يبني جدول توزيعات ربع سنوية تجريبي */
function buildDistributions(
  id: string,
  principal: number,
  rate: number,
  remainingPayments: number,
  paidPayments: number,
  startYear: number,
  startMonth: number,
): Distribution[] {
  const total = remainingPayments + paidPayments;
  const perPayment = Math.round(((principal * (rate / 100)) / 4) * 100) / 100;
  const out: Distribution[] = [];
  for (let i = 0; i < total; i++) {
    const m = (startMonth + i * 3) % 12;
    const y = startYear + Math.floor((startMonth + i * 3) / 12);
    const isLast = i === total - 1;
    out.push({
      id: `${id}-d${i + 1}`,
      date: `${AR_MONTHS[m]} ${y}`,
      amount: isLast ? Math.round(perPayment + principal) : Math.round(perPayment),
      status: i < paidPayments ? "paid" : "due",
    });
  }
  return out;
}

